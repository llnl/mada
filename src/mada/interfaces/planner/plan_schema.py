"""Pydantic models for the MADA Workflow Planner."""

from __future__ import annotations

from pydantic import BaseModel, Field

# Single source of truth for the default LLM model used by the planner AND
# the generated agent configs. Change this one line to swap the default
# across every layer (Pydantic schemas, planner_agent function signature,
# generated JSON config, SYSTEM_PROMPT text).
# Frontend has its own mirror in planner-ui/lib/constants.ts.
DEFAULT_MODEL = "gpt-4o-mini"


class PlannedAgent(BaseModel):
    """An agent in the planned workflow."""

    agent_name: str = Field(description="Unique agent identifier, e.g. 'EducatorAgent'")
    description: str = Field(description="What this agent does in one sentence")
    domain: str = Field(description="Specialization domain, e.g. 'education'")
    mcp_servers: list[str] = Field(
        default_factory=list,
        description="MCP server names this agent connects to",
    )
    instructions: str = Field(description="System prompt defining agent behavior")
    depends_on: list[str] = Field(
        default_factory=list,
        description="Agent names this agent receives input from",
    )


class ExecutionStep(BaseModel):
    """A step in the execution plan."""

    step_number: int
    agents: list[str] = Field(description="Agent names executing in this step")
    description: str = Field(description="What happens in this step")
    parallel: bool = Field(
        default=False,
        description="Whether agents in this step run concurrently",
    )


class PlannedWorkflow(BaseModel):
    """Complete workflow plan generated by the planner agent."""

    task_description: str = Field(description="Original user task description")
    orchestration_type: str = Field(
        default="agent-as-tool",
        description="Orchestration strategy: 'agent-as-tool' (default, faster) or 'magentic'",
    )
    max_turns: int = Field(default=20, description="Max orchestration turns")
    max_stalls: int = Field(default=3, description="Max stalls before aborting")
    model: str = Field(default=DEFAULT_MODEL, description="LLM model for agents")
    agents: list[PlannedAgent] = Field(description="Agents in the workflow")
    execution_steps: list[ExecutionStep] = Field(
        description="Ordered execution steps",
    )
    reasoning: str = Field(
        description="Why these agents and strategy were chosen",
    )


class PlanRequest(BaseModel):
    """Request body for POST /api/plan."""

    task_description: str
    model: str = DEFAULT_MODEL


class GeneratedOutput(BaseModel):
    """Response body for POST /api/generate."""

    json_config: dict
    python_code: str
