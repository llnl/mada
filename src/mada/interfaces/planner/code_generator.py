"""Generate a standalone Python script from a PlannedWorkflow."""

from __future__ import annotations

import json
import textwrap

from .plan_schema import PlannedWorkflow


def generate_code(workflow: PlannedWorkflow, config_filename: str = "workflow_config.json") -> str:
    """Convert a PlannedWorkflow into a runnable Python script string.

    Args:
        workflow: The planned workflow.
        config_filename: Name of the JSON config file the script will load.

    Returns:
        A complete Python script as a string.
    """
    agent_summary = ", ".join(a.agent_name for a in workflow.agents)

    steps_comment = ""
    for step in workflow.execution_steps:
        agents = ", ".join(step.agents)
        par = " (parallel)" if step.parallel else ""
        steps_comment += f"#   {step.step_number}. {agents}{par}: {step.description}\n"

    return f'''\
"""
MADA Workflow: {_safe(workflow.task_description[:80])}

Agents: {agent_summary}
Orchestration: {workflow.orchestration_type}

Execution steps:
{steps_comment.rstrip()}

Generated by MADA Workflow Planner
"""
import asyncio

from mada.core.config import load_config_from_json
from mada.core.database.session_manager import ChatSessionManager
from mada.core.orchestrator import MADAOrchestrator


CONFIG_PATH = "{_safe(config_filename)}"
QUERY = (
    "{_safe(workflow.task_description)}"
)


async def main():
    config = load_config_from_json(CONFIG_PATH)

    session_manager = ChatSessionManager(config.database)
    session_manager.create_new_session()

    async with MADAOrchestrator(
        model_config=config.model,
        database_config=config.database,
        orchestration_config=config.orchestration,
        session_manager=session_manager,
    ) as orchestrator:
        status, tools = await orchestrator.initialize_orchestrator(
            agent_configs=config.agents,
            mcp_servers=config.mcp_servers,
        )
        print(f"Status: {{status}}")
        print(f"Tools available: {{len(tools)}}")

        print("\\n--- Running Workflow ---\\n")
        async for chunk in orchestrator.process_message(QUERY):
            print(chunk, end="", flush=True)
        print("\\n\\n--- Complete ---")


if __name__ == "__main__":
    asyncio.run(main())
'''


def _safe(text: str) -> str:
    """Escape characters that would break Python string literals."""
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
